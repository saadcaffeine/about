#!/usr/bin/env node
/*
 * Build step for the about page. Run after editing the ENTRIES list or the
 * Talks section in index.html:
 *
 *     node tools/build.js
 *
 * 1. Pre-renders the timeline into static HTML inside #timeline-container,
 *    so crawlers and AI answer engines that don't run JavaScript can read
 *    every entry. The in-page script skips rendering when cards exist.
 * 2. Regenerates the Timeline and Talks sections of ABOUT.md so the
 *    markdown mirror always matches the page.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const htmlPath = path.join(root, 'index.html');
const mdPath = path.join(root, 'ABOUT.md');
let html = fs.readFileSync(htmlPath, 'utf8');
let md = fs.readFileSync(mdPath, 'utf8');

const MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
const THEMES = {
  'OPEN-GOVERNANCE': 'Open Governance', 'INCLUSIVE-DESIGN': 'Inclusive Design',
  'TECH-SALVAGE': 'Tech Salvage', 'BIO-MAKING': 'Bio Making',
  'CRITICAL-PLAY': 'Critical Play', 'DIGITAL-EQUITY': 'Digital Equity',
};
const esc = s => String(s).replace(/&(?!(amp|lt|gt|quot|#\d+);)/g, '&amp;')
  .replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const unesc = s => s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/&lt;/g, '<').replace(/&gt;/g, '>');

// ---- Load entries ---------------------------------------------------------
const start = html.indexOf('const ENTRIES');
const end = html.indexOf('];', start) + 2;
if (start < 0) throw new Error('ENTRIES not found in index.html');
const ENTRIES = new Function(html.slice(start, end) + '; return ENTRIES;')();
for (const e of ENTRIES) {
  if (!THEMES[e.theme]) throw new Error(`Unknown theme "${e.theme}" on: ${e.title}`);
  if (e.month !== '—' && !MONTHS.includes(e.month)) throw new Error(`Bad month "${e.month}" on: ${e.title}`);
}
const byYear = {};
ENTRIES.forEach(e => (byYear[e.year] = byYear[e.year] || []).push(e));
const years = Object.keys(byYear).map(Number).sort((a, b) => b - a);
for (const y of years) byYear[y].sort((a, b) => MONTHS.indexOf(b.month) - MONTHS.indexOf(a.month));

// ---- 1. Static timeline HTML (mirrors the in-page renderer) --------------
let tl = '\n';
for (const y of years) {
  tl += `      <div class="year-group" data-year="${y}">\n`;
  tl += `        <h3 class="year-label" aria-label="Year ${y}">${y}</h3>\n`;
  tl += `        <div class="entry-grid">\n`;
  for (const e of byYear[y]) {
    const cls = e.art ? 'entry-card is-art' : 'entry-card';
    const badge = e.art ? '<span class="art-badge" role="img" aria-label="Arts &amp; museum engagement"></span>' : '';
    const asLink = e.url && !e.archive;
    const open = asLink
      ? `<a class="${cls}" data-theme="${e.theme}" href="${esc(e.url)}" target="_blank" rel="noopener noreferrer" aria-label="${esc(`${e.title} — ${e.role} (opens in new tab)${e.art ? ', arts & museum engagement' : ''}`)}">`
      : `<div class="${cls}" data-theme="${e.theme}">`;
    const title = e.archive && e.url
      ? `<a href="${esc(e.url)}" target="_blank" rel="noopener noreferrer" style="text-decoration:none; color:inherit;">${esc(e.title)} ↗</a> <a href="${esc(e.archive)}" aria-label="View archive snapshot" title="Archive snapshot">🗄️</a>`
      : esc(e.title);
    tl += `          ${open}\n`;
    tl += `            <div class="entry-meta"><span class="entry-month">${esc(e.month)}</span> <span class="entry-cat" aria-label="Category: ${esc(e.cat)}">${esc(e.cat)}</span></div>\n`;
    tl += `            <div class="entry-title">${badge}${title}</div>\n`;
    tl += `            <div class="entry-role">${esc(e.role)}${e.url ? ' ↗' : ''}</div>\n`;
    tl += `          ${asLink ? '</a>' : '</div>'}\n`;
  }
  tl += `        </div>\n      </div>\n`;
}
const cStart = html.search(/<div id="timeline-container"[^>]*>/);
if (cStart < 0) throw new Error('#timeline-container not found');
const openTag = html.slice(cStart).match(/<div id="timeline-container"[^>]*>/)[0];
const BEGIN = '<!-- TIMELINE:BEGIN (generated by tools/build.js) -->';
const FINISH = '<!-- TIMELINE:END -->';
const afterOpen = cStart + openTag.length;
let closeAt;
if (html.slice(afterOpen, afterOpen + 200).includes(BEGIN)) {
  closeAt = html.indexOf(FINISH, afterOpen) + FINISH.length;
} else {
  closeAt = afterOpen; // first run: container was empty
}
html = html.slice(0, afterOpen) + '\n      ' + BEGIN + tl + '      ' + FINISH + '\n    ' +
       html.slice(closeAt).replace(/^\s*/, '');
fs.writeFileSync(htmlPath, html);

// ---- 2. ABOUT.md ----------------------------------------------------------
let mdTl = `## Timeline (${years[years.length - 1]}–${years[0]})\n\n`;
for (const y of years) {
  mdTl += `### ${y}\n`;
  for (const e of byYear[y]) {
    let t = e.url ? `[${e.title}](${e.url})` : e.title;
    if (e.archive) t += ` [🗄️](${e.archive})`;
    mdTl += `- **${e.month}** — ${t} · ${e.role} · _${e.cat}_ · \`${THEMES[e.theme]}\`${e.art ? ' 🎨' : ''}\n`;
  }
  mdTl += '\n';
}
const tStart = html.indexOf('<section id="talks"');
const tSec = html.slice(tStart, html.indexOf('</section>', tStart));
let talks = '## Talks & Speaking\n\n';
for (const g of tSec.split('<div class="year-group">').slice(1)) {
  talks += `### ${unesc(g.match(/<p class="year-label">([^<]+)<\/p>/)[1])}\n\n`;
  for (const a of g.split('<article').slice(1)) {
    const cat = unesc(a.match(/<span class="entry-cat">([^<]+)<\/span>/)[1]);
    const th = a.match(/<div class="entry-title">([\s\S]*?)<\/div>/)[1].replace(/<span class="art-badge"[^>]*><\/span>/, '');
    const link = th.match(/<a href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/);
    const title = link ? `[${unesc(link[2].replace(/\s*↗\s*$/, ''))}](${link[1]})` : unesc(th.trim());
    const role = unesc(a.match(/<div class="entry-role">([\s\S]*?)<\/div>/)[1].trim());
    talks += `- **${cat}** — ${title} · ${role}\n`;
  }
  talks += '\n';
}
const swap = (src, head, next, body) => {
  const i = src.indexOf(head), j = src.indexOf(next, i);
  if (i < 0 || j < 0) throw new Error('ABOUT.md section not found: ' + head);
  return src.slice(0, i) + body + src.slice(j);
};
md = swap(md, '## Timeline (', '## Evergreen Projects', mdTl);
md = swap(md, '## Talks & Speaking', '## Network & Advisory', talks);
fs.writeFileSync(mdPath, md);

console.log(`Built: ${ENTRIES.length} timeline entries pre-rendered; ABOUT.md regenerated.`);
